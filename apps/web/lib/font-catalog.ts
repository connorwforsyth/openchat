import type { FontsConfig } from "@workspace/config/schema";

// The fonts `fonts:` in app.config.yaml can pick, all from npm packages so
// builds never download fonts (offline, air-gapped and CI builds all work).
// `scripts/fonts-select.ts` writes `localFont` calls for just the chosen pair
// into `lib/fonts.selected.ts`, so the others are never in the build.
//
// Geist's file is loaded directly because `geist/font/*` fixes the variables
// to `--font-geist-*`, and the theme reads `--font-sans` and `--font-mono`.
// The others are Fontsource's Latin variable subsets.

export interface FontFile {
  /** Relative to apps/web/lib, where the generated file lives. */
  readonly src: string;
  /** The variable font's weight axis, as `localFont` wants it. */
  readonly weight: string;
}

const fontsource = (name: string, weight: string): FontFile => ({
  src: `../node_modules/@fontsource-variable/${name}/files/${name}-latin-wght-normal.woff2`,
  weight,
});

export const sansFonts = {
  figtree: fontsource("figtree", "300 900"),
  geist: {
    src: "../node_modules/geist/dist/fonts/geist-sans/Geist-Variable.woff2",
    weight: "100 900",
  },
  "ibm-plex-sans": fontsource("ibm-plex-sans", "100 700"),
  inter: fontsource("inter", "100 900"),
  manrope: fontsource("manrope", "200 800"),
  "open-sans": fontsource("open-sans", "300 800"),
} as const satisfies Record<FontsConfig["sans"], FontFile>;

export const monoFonts = {
  "geist-mono": {
    src: "../node_modules/geist/dist/fonts/geist-mono/GeistMono-Variable.woff2",
    weight: "100 900",
  },
  "jetbrains-mono": fontsource("jetbrains-mono", "100 800"),
} as const satisfies Record<FontsConfig["mono"], FontFile>;

/** `lib/fonts.selected.ts` for a choice of fonts. */
export const renderSelectedFonts = (fonts: FontsConfig): string => {
  const sans = sansFonts[fonts.sans];
  const mono = monoFonts[fonts.mono];
  return `// Generated by \`fonts:select\` for ${fonts.sans} and ${fonts.mono}. Do not
// edit; it is gitignored and rewritten before every build, dev and typecheck
// run. Only these fonts are in the build (lib/font-catalog.ts).

import localFont from "next/font/local";

const sans = localFont({
  src: ${JSON.stringify(sans.src)},
  variable: "--font-sans",
  weight: ${JSON.stringify(sans.weight)},
});

const mono = localFont({
  adjustFontFallback: false,
  fallback: [
    "ui-monospace",
    "SFMono-Regular",
    "Menlo",
    "Monaco",
    "Liberation Mono",
    "monospace",
  ],
  src: ${JSON.stringify(mono.src)},
  variable: "--font-mono",
  weight: ${JSON.stringify(mono.weight)},
});

/** The classes that set \`--font-sans\` and \`--font-mono\`. */
export const fontClasses = [mono.variable, sans.variable];
`;
};
