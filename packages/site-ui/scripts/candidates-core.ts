// The pure half of `candidates.ts`, so the staleness test (which runs in
// the browser, reading files through Vitest's commands) shares it.

/** As the Site kind's `tailwindCandidates` splits a file. */
const SPLIT = /[\s"'`<>]+/;
const UI_IMPORT = /from "@workspace\/ui\/components\/([a-z-]+)"/g;
// Words a class can't be: code, not markup.
const NOT_A_CLASS = /[{};]|^[A-Z(.,=/]|^\*[*/]/;
const SOURCE = /^[a-z-]+\.tsx?$/;

/** site-ui's own files that blocks are written in, from a directory listing. */
export const ownSources = (names: readonly string[]): readonly string[] =>
  names.filter((name) => SOURCE.test(name)).sort();

/** The `@workspace/ui` components `texts` import, as paths from the repo's packages/. */
export const kitSources = (texts: readonly string[]): readonly string[] =>
  [
    ...new Set(
      texts.flatMap((text) =>
        [...text.matchAll(UI_IMPORT)].map(
          (match) => `ui/src/components/${match[1] ?? ""}.tsx`
        )
      )
    ),
  ].sort();

export const candidatesOf = (texts: readonly string[]): readonly string[] =>
  [
    ...new Set(
      texts
        .flatMap((text) => text.split(SPLIT))
        .filter(
          (word) =>
            word.length > 1 && word.length < 200 && !NOT_A_CLASS.test(word)
        )
    ),
  ].sort();

export const renderCandidates = (
  sources: readonly string[],
  candidates: readonly string[]
): string =>
  [
    "// Generated by scripts/candidates.ts. Don't edit.",
    "",
    "/** The files the candidates were read from, as paths from packages/. */",
    "export const SITE_UI_CANDIDATE_SOURCES: readonly string[] = [",
    ...sources.map((path) => `  ${JSON.stringify(path)},`),
    "];",
    "",
    "/** The words site-ui's blocks are styled with, for a site's Tailwind build. */",
    "export const SITE_UI_CANDIDATES: readonly string[] = [",
    ...candidates.map((word) => `  ${JSON.stringify(word)},`),
    "];",
    "",
  ].join("\n");
