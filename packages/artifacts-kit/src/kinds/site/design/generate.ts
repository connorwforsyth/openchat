import { readFile, writeFile } from "node:fs/promises";

// Writes `generated.ts` from the stacks' `design.md` files, as
// `packages/ai/src/prompts` does for its prompt files: the guides are
// written as Markdown, and every bundler gets the same strings with no
// plugin. `generated.test.ts` fails when it's out of date.
// Run: `bun src/kinds/site/design/generate.ts` in packages/artifacts-kit.

export const DESIGN_FILES = {
  "html-tailwind": "html-tailwind.md",
  "react-ui": "react-ui.md",
} as const;

const here = new URL(".", import.meta.url);

export const readDesignFiles = async (): Promise<Record<string, string>> =>
  Object.fromEntries(
    await Promise.all(
      Object.entries(DESIGN_FILES).map(async ([stack, file]) => [
        stack,
        (await readFile(new URL(file, here), "utf8")).trim(),
      ])
    )
  );

export const renderGenerated = (designs: Record<string, string>): string =>
  [
    "// Generated by generate.ts from the design.md files beside it. Don't edit.",
    "",
    "export const DESIGN_GUIDES = {",
    ...Object.entries(designs).map(
      // As Biome lays out a long string value.
      ([stack, text]) =>
        `  ${JSON.stringify(stack)}:\n    ${JSON.stringify(text)},`
    ),
    "} as const;",
    "",
  ].join("\n");

if (import.meta.main) {
  await writeFile(
    new URL("generated.ts", here),
    renderGenerated(await readDesignFiles())
  );
}
