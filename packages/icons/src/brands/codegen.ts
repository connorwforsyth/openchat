import { z } from "zod";

// Turns lobe-icons' monochrome SVG files into path data (pure). The package
// draws each mark with `fill="currentColor"` paths on one `<svg>`; anything
// else (gradients, `<g>`, strokes, a fixed colour) is refused rather than
// half-copied, so a mark that changes shape upstream fails `icons:generate`.

export const markPathSchema = z.object({
  clipRule: z.enum(["evenodd", "nonzero"]).optional(),
  d: z.string().min(1),
  fillOpacity: z.number().min(0).max(1).optional(),
  fillRule: z.enum(["evenodd", "nonzero"]).optional(),
});
export type MarkPath = z.infer<typeof markPathSchema>;

export const markSchema = z.object({
  paths: z.array(markPathSchema).min(1),
  title: z.string(),
  viewBox: z.string().min(1),
});
export type Mark = z.infer<typeof markSchema>;

const ATTRIBUTE = /([a-zA-Z:-]+)="([^"]*)"/g;
const TAG = /<(\/?)([a-zA-Z]+)([^>]*?)(\/?)>/g;
const TITLE = /<title>([^<]*)<\/title>/;
const ALLOWED_TAGS = new Set(["path", "svg", "title"]);
// Presentation the copy keeps, or drops because it says nothing (`style` is
// lobe's `flex:none`, the size is 1em; we size marks like any other icon).
const SVG_ATTRIBUTES = new Set([
  "clip-rule",
  "fill",
  "fill-rule",
  "height",
  "style",
  "viewBox",
  "width",
  "xmlns",
]);
const PATH_ATTRIBUTES = new Set([
  "clip-rule",
  "d",
  "fill",
  "fill-opacity",
  "fill-rule",
]);

const attributes = (source: string): Map<string, string> =>
  new Map(
    [...source.matchAll(ATTRIBUTE)].map(([, key, value]) => [
      key ?? "",
      value ?? "",
    ])
  );

const rule = (value: string | undefined) =>
  value === "evenodd" || value === "nonzero" ? value : undefined;

/** Why a tag can't be copied, or `undefined` when it can. */
const refusal = (
  name: string,
  found: ReadonlyMap<string, string>
): string | undefined => {
  if (!ALLOWED_TAGS.has(name)) {
    return `unexpected <${name}>`;
  }
  const allowed = name === "svg" ? SVG_ATTRIBUTES : PATH_ATTRIBUTES;
  const unknown = [...found.keys()].find((key) => !allowed.has(key));
  if (name !== "title" && unknown !== undefined) {
    return `unexpected ${unknown} on <${name}>`;
  }
  const fill = found.get("fill");
  return fill === undefined || fill === "currentColor"
    ? undefined
    : `a fixed fill (${fill}) on <${name}>`;
};

const markPath = (
  found: ReadonlyMap<string, string>,
  root: ReadonlyMap<string, string> | undefined
): MarkPath => {
  const opacity = found.get("fill-opacity");
  const fillRule = rule(found.get("fill-rule") ?? root?.get("fill-rule"));
  const clipRule = rule(found.get("clip-rule") ?? root?.get("clip-rule"));
  return {
    d: found.get("d") ?? "",
    ...(fillRule === undefined ? {} : { fillRule }),
    ...(clipRule === undefined ? {} : { clipRule }),
    ...(opacity === undefined ? {} : { fillOpacity: Number(opacity) }),
  };
};

/** One SVG file's mark, or why it can't be copied. */
export const parseMarkSvg = (
  svg: string
):
  | { readonly mark: Mark; readonly ok: true }
  | { readonly error: string; readonly ok: false } => {
  let root: Map<string, string> | undefined;
  const paths: MarkPath[] = [];
  for (const [, closing, name = "", rest = ""] of svg.matchAll(TAG)) {
    if (closing === "/") {
      continue;
    }
    const found = attributes(rest);
    const error = refusal(name, found);
    if (error !== undefined) {
      return { error, ok: false };
    }
    if (name === "svg") {
      root ??= found;
    } else if (name === "path") {
      paths.push(markPath(found, root));
    }
  }
  const parsed = markSchema.safeParse({
    paths,
    title: TITLE.exec(svg)?.[1] ?? "",
    viewBox: root?.get("viewBox"),
  });
  return parsed.success
    ? { mark: parsed.data, ok: true }
    : { error: "no viewBox or no paths", ok: false };
};

/** The checked-in module for `marks`, before formatting. */
export const generatedModule = (
  version: string,
  marks: Readonly<Record<string, Mark>>
): string =>
  [
    "// Generated by `bun run icons:generate` (packages/icons) from",
    `// @lobehub/icons-static-svg ${version}: MIT, Copyright (c) 2023 LobeHub;`,
    "// see LICENSE and NOTICE beside this file. Don't edit it: change",
    "// `brands.ts` or the package version and regenerate. `brands.test.ts`",
    "// fails when the two disagree.",
    "",
    'import type { Mark } from "./codegen";',
    "",
    `export const LOBE_ICONS_VERSION = ${JSON.stringify(version)};`,
    "",
    `export const marks: Readonly<Record<string, Mark>> = ${JSON.stringify(marks, null, 2)};`,
    "",
  ].join("\n");
