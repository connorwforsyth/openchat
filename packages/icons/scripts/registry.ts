import {
  fallbackIconSet,
  type IconPlatform,
  type IconSetId,
} from "../src/set-ids";

// Pure helpers behind `icons:select` and `icons:gaps`. Set files are read as
// text, not imported: the native sets import `lucide-react-native`, which isn't
// installed on web-only machines, and parsing is far faster than loading
// thousands of icon modules just to list their names.

export type Result<T, E> = { ok: true; value: T } | { error: E; ok: false };

const exportPattern = /^export const (\w+Icon)\b/gm;

/** Names a set file maps, from its `export const FooIcon` declarations. */
export function exportedIconNames(source: string): string[] {
  return [...source.matchAll(exportPattern)].map((match) => match[1] ?? "");
}

const bindingPattern = /^export const (\w+Icon): \w+ = (\w+);$/gm;
const lucideModulePattern = /\bfrom "(lucide-react(?:-native)?)";/;

/** Which lucide export draws each name, from the fallback set's source. */
export interface LucideBindings {
  readonly exports: ReadonlyMap<string, string>;
  /** `lucide-react` or `lucide-react-native`. */
  readonly module: string;
}

/** Reads `export const FooIcon: Icon = Foo;` lines from `sets/lucide*.ts`. */
export function lucideBindings(source: string): LucideBindings | undefined {
  const module = lucideModulePattern.exec(source)?.[1];
  if (!module) {
    return;
  }
  const exports = new Map(
    [...source.matchAll(bindingPattern)].map(
      ([, name = "", glyph = ""]) => [name, glyph] as const
    )
  );
  return { exports, module };
}

export interface Selection {
  /** Names the chosen set lacks, drawn by lucide instead. */
  fallback: string[];
  /** Names the chosen set draws. */
  fromSet: string[];
}

export function resolveSelection(
  names: readonly string[],
  available: ReadonlySet<string>
): Selection {
  return {
    fallback: names.filter((name) => !available.has(name)),
    fromSet: names.filter((name) => available.has(name)),
  };
}

function exportBlock(specifiers: readonly string[], from: string): string {
  if (specifiers.length === 0) {
    return "";
  }
  // Formatted the way Biome would, so the generated file passes lint.
  const oneLine = `export { ${specifiers.join(", ")} } from "${from}";`;
  if (oneLine.length <= 80) {
    return `${oneLine}\n`;
  }
  const lines = specifiers.map((specifier) => `  ${specifier},`).join("\n");
  return `export {\n${lines}\n} from "${from}";\n`;
}

/**
 * A set's gaps, re-exported straight from lucide rather than through
 * `sets/lucide.ts`. Importing any name from that file drags in every icon it
 * imports (Turbopack keeps a module's imports once one of its exports is
 * used), which put all of lucide in the bundle beside the chosen set. A
 * re-export lets the bundler follow each name to its own icon module, so only
 * the gaps something renders are bundled.
 */
function fallbackBlock(
  names: readonly string[],
  lucide: LucideBindings | undefined,
  fallbackFile: string
): string {
  const direct = names.flatMap((name) => {
    const glyph = lucide?.exports.get(name);
    return glyph ? [`${glyph} as ${name}`] : [];
  });
  const viaFile = names.filter((name) => !lucide?.exports.has(name));
  return [
    exportBlock(direct, lucide?.module ?? fallbackFile),
    exportBlock(viaFile, fallbackFile),
  ].join("");
}

/** Source of `src/selected.ts` / `src/selected.native.ts`. */
export function renderSelection({
  lucide,
  platform,
  selection,
  setFile,
  setId,
}: {
  /** The fallback set's bindings, so gaps can skip `sets/lucide*.ts`. */
  lucide?: LucideBindings;
  platform: IconPlatform;
  selection: Selection;
  /** Import specifier of the chosen set, or undefined if not implemented. */
  setFile: string | undefined;
  setId: IconSetId;
}): string {
  const suffix = platform === "native" ? ".native" : "";
  const fallbackFile = `./sets/${fallbackIconSet}${suffix}`;
  const header = [
    `// Generated by \`icons:select\` for the ${setId} set. Do not edit; it is`,
    "// gitignored and rewritten before every build, dev and typecheck run.",
    "// This file is the package entry (`@workspace/icons[/native]`): every name",
    "// comes from exactly one set, so bundlers never see the others.",
    "",
    platform === "native"
      ? 'export type { NativeIcon, NativeIconProps } from "./types.native";'
      : 'export type { Icon, IconProps } from "./types";',
    "",
  ].join("\n");
  const fromSet =
    setFile && setId !== fallbackIconSet
      ? exportBlock(selection.fromSet, setFile)
      : "";
  // With lucide chosen, or a set with no file for this platform, every name
  // comes from the typed lucide set file; only a real set's gaps go direct.
  const allLucide = setId === fallbackIconSet || !setFile;
  const fallback = allLucide
    ? exportBlock([...selection.fromSet, ...selection.fallback], fallbackFile)
    : fallbackBlock(selection.fallback, lucide, fallbackFile);
  const fallbackComment =
    setId !== fallbackIconSet && fallback
      ? `// Not in ${setId} yet, so lucide draws these (\`bun run icons:gaps\`).\n`
      : "";
  return [header, fromSet, fallbackComment, fallback]
    .filter(Boolean)
    .join("\n")
    .replace(/\n{3,}/g, "\n\n");
}

export type GapReport = {
  platform: IconPlatform;
  missing: string[];
  setId: IconSetId;
}[];

export function findGaps(
  names: readonly string[],
  sets: readonly {
    available: ReadonlySet<string> | undefined;
    platform: IconPlatform;
    setId: IconSetId;
  }[]
): GapReport {
  return sets.map(({ available, platform, setId }) => ({
    missing: names.filter((name) => !available?.has(name)),
    platform,
    setId,
  }));
}

export function formatGapReport(report: GapReport, total: number): string {
  return report
    .map(({ missing, platform, setId }) => {
      const label = `${setId} (${platform})`;
      if (missing.length === 0) {
        return `${label}: complete (${total}/${total})`;
      }
      if (missing.length === total) {
        return `${label}: not implemented, all ${total} fall back to lucide`;
      }
      return `${label}: ${total - missing.length}/${total}, falls back to lucide for ${missing.join(", ")}`;
    })
    .join("\n");
}
