import { describe, expect, it } from "vitest";

import { GENERATED_CATALOG } from "./generated";
import {
  buildCatalog,
  gatewayEndpointsSchema,
  modelsDevSchema,
  pricesFromModelsDev,
  renderCatalog,
  throughputOf,
} from "./refresh";
import { generatedCatalogSchema } from "./schema";

const provider = (models: Record<string, unknown>) => ({
  id: "x",
  models,
  name: "X",
});

const modelsDev = modelsDevSchema.parse({
  // Out of order on purpose: the snapshot sorts them.
  anthropic: provider(
    Object.fromEntries([
      ["claude-b", { cost: { cache_read: 0.01, input: 0.1, output: 0.5 } }],
      ["claude-free", { cost: { input: 0, output: 0 } }],
      ["claude-a", { cost: { input: 3, output: 15 } }],
      ["claude-unlisted", { name: "No cost given" }],
    ])
  ),
  google: provider({}),
  openai: provider({ "gpt-x": { cost: { input: 0.075, output: 0.3 } } }),
  "some-other-provider": provider({ m: { cost: { input: 1, output: 1 } } }),
  vercel: provider({
    "anthropic/claude-b": {
      cost: {
        cache_read: 0.01,
        cache_write: 0.125,
        input: 0.1,
        output: 0.5,
        tiers: [
          { input: 0.5, output: 2.5, tier: { size: 100_000, type: "context" } },
        ],
      },
    },
  }),
});

describe("pricesFromModelsDev", () => {
  const prices = pricesFromModelsDev(modelsDev);

  it("converts USD per million tokens to integer micro-USD", () => {
    expect(prices.anthropic["claude-b"]).toEqual({
      cachedInputMicros: 10_000,
      inputMicros: 100_000,
      outputMicros: 500_000,
    });
    expect(prices.openai["gpt-x"]).toEqual({
      inputMicros: 75_000,
      outputMicros: 300_000,
    });
  });

  it("keeps free models and leaves out ones with no price", () => {
    expect(prices.anthropic["claude-free"]).toEqual({
      inputMicros: 0,
      outputMicros: 0,
    });
    expect(prices.anthropic).not.toHaveProperty("claude-unlisted");
  });

  it("keeps only the sources we price, at their base rate", () => {
    expect(Object.keys(prices)).toEqual([
      "anthropic",
      "google",
      "openai",
      "vercel",
    ]);
    expect(prices.vercel["anthropic/claude-b"]).toEqual(
      prices.anthropic["claude-b"]
    );
  });

  it("sorts models by id so a refresh diffs cleanly", () => {
    expect(Object.keys(prices.anthropic)).toEqual([
      "claude-a",
      "claude-b",
      "claude-free",
    ]);
  });
});

describe("throughputOf", () => {
  const endpoints = (...rows: [string, number | null][]) =>
    gatewayEndpointsSchema.parse({
      data: {
        endpoints: rows.map(([name, p50]) => ({
          provider_name: name,
          throughput_last_1h: p50 === null ? null : { p50, p95: p50 },
        })),
      },
    });

  it("takes the maker's own endpoint", () => {
    expect(
      throughputOf(
        "anthropic/claude-opus-5.5",
        endpoints(["bedrock", 85], ["anthropic", 267.6], ["vertex", 111])
      )
    ).toBe(268);
  });

  it("else the median of the endpoints that report one", () => {
    expect(
      throughputOf(
        "alibaba/qwen",
        endpoints(["a", 80], ["b", null], ["c", 100])
      )
    ).toBe(90);
    expect(
      throughputOf("x/y", endpoints(["a", 10], ["b", 30], ["c", 20]))
    ).toBe(20);
  });

  it("counts a trickle under one token a second as 1", () => {
    expect(throughputOf("x/y", endpoints(["x", 0.3]))).toBe(1);
  });

  it("is unknown when nothing reports", () => {
    expect(throughputOf("x/y", endpoints(["a", null]))).toBeUndefined();
  });
});

describe("the generated catalogue", () => {
  const catalog = generatedCatalogSchema.parse(GENERATED_CATALOG);

  it("is valid, and has prices from every source and some speeds", () => {
    for (const models of Object.values(catalog.prices)) {
      expect(Object.keys(models).length).toBeGreaterThan(0);
    }
    expect(Object.keys(catalog.tokensPerSecond).length).toBeGreaterThan(0);
  });

  it("renders with a header that says how to update it", () => {
    const rendered = renderCatalog(
      buildCatalog(pricesFromModelsDev(modelsDev), [], catalog.fetchedAt)
    );
    expect(
      rendered.startsWith("// Generated by `bun run catalog:refresh`")
    ).toBe(true);
  });
});
