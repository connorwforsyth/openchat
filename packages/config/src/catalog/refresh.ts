import { z } from "zod";

import type { ModelPrice } from "../schema";
import {
  CATALOG_SOURCES,
  type GeneratedCatalog,
  type PriceSource,
  priceSourceSchema,
} from "./schema";

// The pure half of `scripts/refresh-catalog.ts`: the upstream shapes we read
// and how they become the generated catalogue. Both sources are public and
// keyless. Prices: models.dev (MIT, Copyright (c) 2025 models.dev). Speed:
// the Vercel AI Gateway's per-endpoint throughput over the last hour.

/** USD per million tokens. */
const usdSchema = z.number().min(0);

const modelsDevProviderSchema = z.object({
  models: z.record(
    z.string(),
    z.object({
      cost: z
        .object({
          cache_read: usdSchema.optional(),
          input: usdSchema,
          output: usdSchema,
        })
        .optional(),
    })
  ),
});

/** The part of models.dev's `api.json` we read; the rest is ignored. */
export const modelsDevSchema = z.object(
  Object.fromEntries(
    priceSourceSchema.options.map((source) => [source, modelsDevProviderSchema])
  ) as Record<PriceSource, typeof modelsDevProviderSchema>
);
export type ModelsDev = z.infer<typeof modelsDevSchema>;

/** The Gateway's `/v1/models`: which ids are language models. */
export const gatewayModelsSchema = z.object({
  data: z.array(z.object({ id: z.string().min(1), type: z.string() })),
});

/** The Gateway's `/v1/models/<id>/endpoints`: one entry per upstream provider. */
export const gatewayEndpointsSchema = z.object({
  data: z.object({
    endpoints: z.array(
      z.object({
        provider_name: z.string(),
        throughput_last_1h: z
          .object({ p50: z.number().min(0).nullish() })
          .nullish(),
      })
    ),
  }),
});
export type GatewayEndpoints = z.infer<typeof gatewayEndpointsSchema>;

const micros = (usd: number): number => Math.round(usd * 1_000_000);

const sorted = <T>(entries: readonly (readonly [string, T])[]) =>
  Object.fromEntries(
    [...entries].sort(([a], [b]) => (a < b ? -1 : Number(a > b)))
  );

/**
 * models.dev's list prices as integer micro-USD per million tokens, models
 * without a price left out. Cache writes and long-context tiers aren't kept:
 * the usage we record has no cache-write count, and a run's tokens are summed
 * over its steps, so no single call's context size is known.
 */
export const pricesFromModelsDev = (
  catalog: ModelsDev
): GeneratedCatalog["prices"] =>
  Object.fromEntries(
    priceSourceSchema.options.map((source) => [
      source,
      sorted(
        Object.entries(catalog[source].models).flatMap(([id, { cost }]) => {
          if (!cost) {
            return [];
          }
          const price: ModelPrice = {
            ...(cost.cache_read === undefined
              ? {}
              : { cachedInputMicros: micros(cost.cache_read) }),
            inputMicros: micros(cost.input),
            outputMicros: micros(cost.output),
          };
          return [[id, price] as const];
        })
      ),
    ])
  ) as GeneratedCatalog["prices"];

/** At least 1: a model that reports a trickle is slow, not unknown. */
const wholeTokens = (perSecond: number): number =>
  Math.max(1, Math.round(perSecond));

/**
 * A model's typical output speed in tokens per second: the median over the
 * last hour on its maker's own endpoint (`anthropic` for an `anthropic/…`
 * id), else the median across the endpoints that report one.
 */
export const throughputOf = (
  id: string,
  { data }: GatewayEndpoints
): number | undefined => {
  const [creator] = id.split("/");
  const reported = data.endpoints.flatMap((endpoint) => {
    const p50 = endpoint.throughput_last_1h?.p50;
    return typeof p50 === "number" && p50 > 0
      ? [{ p50, provider: endpoint.provider_name }]
      : [];
  });
  const own = reported.find((endpoint) => endpoint.provider === creator);
  if (own) {
    return wholeTokens(own.p50);
  }
  const values = reported.map((endpoint) => endpoint.p50).sort((a, b) => a - b);
  if (values.length === 0) {
    return;
  }
  const middle = Math.floor(values.length / 2);
  const median =
    values.length % 2 === 1
      ? (values[middle] ?? 0)
      : ((values[middle - 1] ?? 0) + (values[middle] ?? 0)) / 2;
  return wholeTokens(median);
};

export const buildCatalog = (
  prices: GeneratedCatalog["prices"],
  speed: readonly (readonly [string, number])[],
  fetchedAt: string
): GeneratedCatalog => ({
  fetchedAt,
  prices,
  sources: CATALOG_SOURCES,
  tokensPerSecond: sorted(speed),
});

/** The generated module, with the header that says not to edit it. */
export const renderCatalog = (catalog: GeneratedCatalog): string =>
  [
    "// Generated by `bun run catalog:refresh` in packages/config. Don't edit;",
    "// run it again to update. Prices: models.dev (MIT, Copyright (c) 2025",
    "// models.dev). Speed: the Vercel AI Gateway's public endpoint stats.",
    "",
    `export const GENERATED_CATALOG = ${JSON.stringify(catalog, null, 2)};`,
    "",
  ].join("\n");
